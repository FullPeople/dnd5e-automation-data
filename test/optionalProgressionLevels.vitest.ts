import { expect, test } from 'vitest';
import { createIdentity } from '../src/identity.ts';
import { deriveStructured } from '../src/derive/structured/index.ts';
import { makeContext } from '../src/derive/structured/common.ts';
import { deriveCorpus } from '../src/derive/index.ts';
import { validateAutomation } from '../src/validate/index.ts';
import type { Material } from '../src/derive/catalogue.ts';
import type { InputManifest } from '../src/fetch/manifest.ts';

const gap = { family: 'featureProgression', code: 'optional-progression-shape', ref: 'optionalfeatureProgression' };
const run = (groups: unknown[]) => {
  const row: Material = { identity: createIdentity({ kind: 'class', source: 'PHB', engName: 'Synthetic Schedule' }),
    raw: { optionalfeatureProgression: groups }, namespace: 'kiwee', files: ['data/synthetic.json'], expansion: 'source' };
  return deriveStructured(row, makeContext([row]));
};
const group = (progression: Record<string, number>) => ({ featureType: ['EI'], progression });

test.each(['01', '1.0', '1e0', '+1', ' 1 ', '0x1'])('rejects a schedule whose %s key collides with level 1', alias => {
  const progression = Object.freeze({ '1': 1, [alias]: 2 }), before = JSON.stringify(progression);
  const out = run([group(progression)]);
  expect(out.mechanics.grants).toBeUndefined();
  expect(out.unsupported).toEqual([gap]);
  expect(JSON.stringify(progression)).toBe(before);
});

test('two noncanonical keys cannot bypass the normalized-level collision check', () => {
  const out = run([group({ '01': 1, '1.0': 2 })]);
  expect(out.mechanics.grants).toBeUndefined();
  expect(out.unsupported).toEqual([gap]);
});

test.each([0, 2])('equal duplicate quotas of %s do not silently merge or disappear', count => {
  const out = run([group({ '2': count, '02': count })]);
  expect(out.mechanics.grants).toBeUndefined();
  expect(out.unsupported).toEqual([gap]);
});

test('a collision rejects its whole group while preserving other group keys and cumulative totals', () => {
  const out = run([group({ '1': 1, '01': 2, '5': 3 }), group({ '*': 1, '3': 2, '20': 0 })]);
  expect(out.unsupported).toEqual([gap]);
  expect(out.mechanics.grants).toEqual([{ type: 'feature', key: 'optionalfeature:1', atLevel: 0,
    choose: { count: 1, filter: { kind: 'optionalfeature', featureType: ['EI'] } },
    choiceProgression: [{ level: 0, count: 1 }, { level: 3, count: 2 }, { level: 20, count: 0 }] }]);
});

test('a malformed source schedule still produces a valid public pending draft', () => {
  const input: InputManifest['inputs'][number] = { namespace: 'kiwee', path: 'data/synthetic.json', role: 'catalog',
    url: 'https://example.org/data/synthetic.json', sha256: 'a'.repeat(64), bytes: 100, fetchedAt: '2026-10-18T00:00:00Z' };
  const body = { class: [{ ENG_name: 'Synthetic Schedule', source: 'PHB', optionalfeatureProgression: [group({ '1': 1, '01': 2 })] }] };
  const envelope = deriveCorpus([{ input, body }], { toolVersion: 'synthetic', inputs: [input] }).envelope;
  envelope.versionLock.kiweeChangelogDate = '2026-10-18'; envelope.versionLock.foundryMigrationVersion = [3];
  expect(() => validateAutomation(envelope)).not.toThrow();
  expect(envelope.records).toHaveLength(1);
  expect(envelope.records[0]).toMatchObject({ verdict: 'needsAnnotation', autoGenerated: true, unsupported: [gap] });
  expect(envelope.records[0].mechanics?.grants).toBeUndefined();
});

test('ordinary sparse object levels and the existing wildcard remain unchanged', () => {
  const out = run([group({ '20': 3, '1': 0, '4': 2, '*': 1 })]);
  expect(out.unsupported).toEqual([]);
  expect(out.mechanics.grants).toHaveLength(1);
  expect(out.mechanics.grants![0].choiceProgression).toEqual([{ level: 0, count: 1 }, { level: 1, count: 0 }, { level: 4, count: 2 }, { level: 20, count: 3 }]);
});

test('this collision fix preserves existing noncolliding level coercion', () => {
  const out = run([group({ '02': 1, '3.0': 2 })]);
  expect(out.unsupported).toEqual([]);
  expect(out.mechanics.grants![0].choiceProgression).toEqual([{ level: 2, count: 1 }, { level: 3, count: 2 }]);
});
