import {expect,it} from 'vitest';
import {readFileSync} from 'node:fs';
import {createIdentity,identityKey} from '../src/identity.ts';
import {automationErrors,overlayErrors,recordEdition} from '../src/validate/index.ts';
import type {AutomationEnvelope,AutomationRecord} from '../src/protocol.ts';

const fixture=JSON.parse(readFileSync('fixtures/shared/source-identifiers.json','utf8')) as {acceptedSources:string[];distinctSources:string[];rejectedSources:string[]};
const record=(source:string):AutomationRecord=>({identity:createIdentity({packId:'kiwee-homebrew',kind:'feat',source,engName:'Authored source-identity sentinel'}),verdict:'needsAnnotation',autoGenerated:true,provenance:[{layer:'structured',ref:'data/authored-source-identity.json'}],unsupported:[{family:'source-identity',code:'rule-review-pending'}]});
const envelope=(records:AutomationRecord[]):AutomationEnvelope=>({schemaVersion:1,protocol:3,versionLock:{kiweeChangelogVersion:'authored',kiweeChangelogDate:'2026-11-06',fetchedAt:'2026-11-06T00:00:00Z',foundryMigrationVersion:[3],toolVersion:'authored',inputs:[{url:'https://example.invalid/authored-source-identity.json',path:'data/authored-source-identity.json',namespace:'kiwee-homebrew',role:'catalog',sha256:'a'.repeat(64),bytes:1}]},records});

it.each(fixture.acceptedSources)('preserves declared source identifier %s through the current envelope validator',source=>{
 const row=record(source),value=envelope([row]),before=structuredClone(value);
 expect(automationErrors(value)).toEqual([]);expect(value).toEqual(before);
 expect(row.identity.source).toBe(source.toUpperCase());expect(decodeURIComponent(row.identity.key.split(':')[2])).toBe(source.toLowerCase());
 expect(row.verdict).toBe('needsAnnotation');expect(recordEdition(row)).toBeUndefined();
});

it('keeps punctuation-bearing source codes distinct for entries with the same display identity',()=>{
 const records=fixture.distinctSources.map(record);
 expect(new Set(records.map(row=>row.identity.key)).size).toBe(4);expect(automationErrors(envelope(records))).toEqual([]);
 const original=createIdentity({kind:'feat',source:'PHB',engName:'Authored source-identity sentinel'}),revised=createIdentity({kind:'feat',source:'XPHB',engName:'Authored source-identity sentinel'});
 expect(original.key).not.toBe(revised.key);expect(records.every(row=>row.identity.key!==original.key&&row.identity.key!==revised.key)).toBe(true);
});

it('rejects reference separators, paths, escapes, control characters and noncanonical spaces without mutation',()=>{
 for(const source of fixture.rejectedSources){
  const row=record('BOOK');row.identity.source=source;row.identity.key=identityKey(row.identity);const value=envelope([row]),before=structuredClone(value);
  expect(automationErrors(value).length,JSON.stringify(source)).toBeGreaterThan(0);expect(value).toEqual(before);
 }
});

it('permits later explicit review overlays with the same identity boundaries and no automatic promotion',()=>{
 const overlay=(source:string)=>({identity:record(source).identity,verdict:'unsupported',unsupported:[{family:'authored',code:'review-pending'}],reviewer:'human:authored',reviewedAt:'2026-11-06',batch:'source-identity-boundary',evidence:{page:1,quote:'Authored boundary sentinel'}});
 const rows=fixture.acceptedSources.map(overlay),before=structuredClone(rows);
 expect(overlayErrors(rows)).toEqual([]);expect(rows).toEqual(before);expect(rows.every(row=>row.verdict==='unsupported')).toBe(true);
 for(const source of fixture.rejectedSources){
  const row=overlay('BOOK');row.identity.source=source;row.identity.key=identityKey(row.identity);const snapshot=structuredClone(row);
  expect(overlayErrors([row]).length,JSON.stringify(source)).toBeGreaterThan(0);expect(row).toEqual(snapshot);
 }
});
