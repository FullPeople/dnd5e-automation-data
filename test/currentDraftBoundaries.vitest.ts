import {expect,it} from 'vitest';
import {createIdentity} from '../src/identity.ts';
import {deriveStructured} from '../src/derive/structured/index.ts';
import {deriveFoundry} from '../src/derive/foundry/index.ts';
import {makeContext} from '../src/derive/structured/common.ts';
import {schemaErrors} from '../src/validate/index.ts';
import type {Material,Raw} from '../src/derive/catalogue.ts';
import type {AutomationEnvelope,Mechanics} from '../src/protocol.ts';

const material=(kind:string,engName:string,source='PHB',raw:Raw={}):Material=>({identity:createIdentity({kind,source,engName}),raw:{ENG_name:engName,source,...raw},namespace:'kiwee',files:['authored.json'],expansion:'source'});
const owner=()=>material('feat','Authored immunity owner');
const envelope=(mechanics:Mechanics,kind='feat'):AutomationEnvelope=>({schemaVersion:1,protocol:3,versionLock:{kiweeChangelogVersion:'authored',kiweeChangelogDate:'2026-11-06',fetchedAt:'2026-11-06T00:00:00Z',foundryMigrationVersion:[3],toolVersion:'authored',inputs:[{url:'https://example.invalid/authored.json',path:'authored.json',namespace:'kiwee',role:'catalog',sha256:'a'.repeat(64),bytes:1}]},records:[{identity:material(kind,'Authored boundary').identity,verdict:'needsAnnotation',autoGenerated:true,provenance:[{layer:'structured',ref:'authored.json'}],unsupported:[],mechanics}]});
function immunity(value:string,context:Material[]=[],effect:Raw={}){
 const subject=owner(),raw={migrationVersion:3,effects:[{transfer:true,changes:[{key:'system.traits.ci.value',mode:'ADD',value}],...effect}]},before=structuredClone(raw);
 const result=deriveFoundry(raw,subject,makeContext([subject,...context]));expect(raw).toEqual(before);return result;
}

it('validates a cumulative book capacity without truncating the twenty bounded level increments',()=>{
 const row=material('class','Authored extended book','HB',{spellsKnownProgressionFixed:Array(20).fill(100)}),before=structuredClone(row),result=deriveStructured(row,makeContext([row]));
 expect(result.mechanics.classModel?.bookProgression).toEqual(Array.from({length:20},(_,i)=>(i+1)*100));expect(row).toEqual(before);
 expect(schemaErrors(envelope(result.mechanics,'class'))).toEqual([]);
});

it('retains all other progression limits and rejects a book capacity outside its representable cumulative bound',()=>{
 for(const model of [{bookProgression:[2001]},{knownProgression:[101]},{preparedProgression:[101]},{cantripProgression:[101]},{bookProgression:Array(21).fill(1)}])expect(schemaErrors(envelope({classModel:model},'class')).length).toBeGreaterThan(0);
 for(const value of [[101],[-1],[1.5],[null]]){
  const row=material('class','Authored invalid increment','HB',{spellsKnownProgressionFixed:value}),result=deriveStructured(row,makeContext([row]));
  expect(result.mechanics.classModel?.bookProgression).toBeUndefined();expect(result.unsupported).toContainEqual(expect.objectContaining({code:'book-progression'}));
 }
});

it('models a declared native disease-immunity ID without requiring a same-name third-party condition',()=>{
 const result=immunity('diseased');expect(result.mechanics.modifiers).toEqual([{target:'conditionImmune:diseased',op:'set',value:true}]);expect(schemaErrors(envelope(result.mechanics))).toEqual([]);
});

it('native immunity does not change when an unrelated same-name condition is added or removed',()=>{
 const foreign=material('condition','Diseased','HB'),before=structuredClone(foreign),without=immunity('diseased'),withForeign=immunity('diseased',[foreign]);
 expect(withForeign.mechanics).toEqual(without.mechanics);expect(withForeign.mechanics.modifiers).toEqual([{target:'conditionImmune:diseased',op:'set',value:true}]);expect(foreign).toEqual(before);
 expect(schemaErrors(envelope(withForeign.mechanics))).toEqual([]);
});

it('does not borrow poison damage or a custom condition name to invent a native condition-immunity ID',()=>{
 for(const value of ['poison','authoredhazard']){
  const foreign=material('condition',value,'HB'),result=immunity(value,[foreign]);
  expect(result.mechanics.modifiers||[]).toEqual([]);expect(result.mechanics.effects?.[0].changes).toEqual([]);
  expect(result.unsupported).toContainEqual(expect.objectContaining({code:'unresolved-effect-token'}));expect(schemaErrors(envelope(result.mechanics))).toEqual([]);
 }
});

it('retains explicit native surprise immunity without inferring a feature name or resolving a catalog entry',()=>{
 expect(immunity('surprised').mechanics.modifiers).toEqual([{target:'conditionImmune:surprised',op:'set',value:true}]);
});

it('recognizing a native ID does not turn timed, disabled or item effects into unconditional ownership immunity',()=>{
 for(const effect of [{disabled:true},{duration:{rounds:1}}]){
  const result=immunity('diseased',[],effect);expect(result.mechanics.modifiers||[]).toEqual([]);expect(result.mechanics.effects?.[0].changes).toEqual([{target:'conditionImmune:diseased',op:'set',value:true}]);expect(result.mechanics.effects?.[0].deferred).toBe(true);
 }
 const subject=material('item','Authored item'),raw={migrationVersion:3,effects:[{transfer:true,changes:[{key:'system.traits.ci.value',mode:'ADD',value:'diseased'}]}]},result=deriveFoundry(raw,subject,makeContext([subject]));
 expect(result.mechanics.modifiers||[]).toEqual([]);expect(result.mechanics.effects?.[0].deferred).toBe(true);
 const unknown=deriveFoundry({...raw,migrationVersion:4},subject,makeContext([subject]));expect(unknown.mechanics).toEqual({});expect(unknown.unsupported).toContainEqual(expect.objectContaining({code:'unreviewed-migration-version'}));
});
