import { expect, test } from 'vitest';
import { createIdentity } from '../src/identity.ts';
import { automationErrors, publicArtifact, schemaErrors, snapshotRecordErrors } from '../src/validate/index.ts';
import type { AutomationEnvelope, AutomationRecord } from '../src/protocol.ts';

const record = (kind: string, source: string, name: string): AutomationRecord => ({
  identity: createIdentity({ kind, source, engName: name }), verdict: 'needsAnnotation', autoGenerated: true,
  provenance: [{ layer: 'structured', ref: 'data/synthetic.json' }], unsupported: [{ family: 'synthetic', code: 'eligibility-pending' }],
});
const envelope = (source: string, filter: Record<string, string | number | string[]>): AutomationEnvelope => {
  const owner = record('optionalfeature', source, 'Synthetic Invocation');
  owner.mechanics = { grants: [{ type: 'spell', choose: { count: 1, filter } }] };
  const spell = record('spell', source, 'Synthetic Spell');
  spell.mechanics = { spellModel: { level: 1, ...(filter.class ? { classes: [{ engName: String(filter.class), source: String(filter.classSource) }] } : {}) } };
  return { schemaVersion: 1, protocol: 3, versionLock: { kiweeChangelogVersion: 'synthetic', kiweeChangelogDate: '2026-10-13', fetchedAt: '2026-10-13T00:00:00Z', foundryMigrationVersion: [3], toolVersion: 'synthetic', inputs: [{ url: 'https://example.org/synthetic.json', path: 'synthetic.json', namespace: 'kiwee', role: 'catalog', sha256: 'a'.repeat(64), bytes: 1 }] }, records: [owner, spell] };
};
const pairs = [{ owner: 'PHB', foreign: 'XPHB' }, { owner: 'XPHB', foreign: 'PHB' }];
const variants = (source: string) => [source.toLowerCase(), source[0] + source.slice(1).toLowerCase(), ` ${source} `];

test.each(pairs.flatMap(({ owner, foreign }) => variants(foreign).map(selector => ({ owner, foreign, selector }))))('$owner rejects a mixed source selector containing canonical alias $selector', ({ owner, foreign, selector }) => {
  const value = envelope(owner, { level: 1, source: [owner, selector] }), before = structuredClone(value);
  expect(createIdentity({ kind: 'spell', source: selector, engName: 'Synthetic' }).source).toBe(foreign);
  expect(schemaErrors(value)).toEqual([]);
  // A valid same-edition candidate cannot conceal an additional foreign scope.
  expect(automationErrors(value)).toContainEqual({ code: 'edition-reference', path: '/records/0/mechanics/grants/0/choose/filter', message: 'A spell filter crosses the edition boundary' });
  expect(automationErrors(value).some(error => error.code === 'spell-filter')).toBe(false);
  expect(() => publicArtifact(value)).toThrow('edition-reference');
  expect(snapshotRecordErrors(value.records[0]).map(error => [error.code, error.path])).toEqual([['edition-reference', '/mechanics/grants/0/choose/filter']]);
  expect(value).toEqual(before);
});

test.each(pairs.flatMap(({ owner, foreign }) => variants(foreign).map(classSource => ({ owner, classSource }))))('$owner rejects a foreign class-source alias $classSource', ({ owner, classSource }) => {
  const value = envelope(owner, { level: 1, class: 'Synthetic Class', classSource });
  expect(schemaErrors(value)).toEqual([]);
  expect(automationErrors(value).map(error => error.code)).toEqual(['edition-reference']);
});

test.each(pairs.map(({ owner }) => owner))('same-edition %s aliases keep a pending draft and do not mutate selectors', source => {
  const value = envelope(source, { level: 1, source: [source, source.toLowerCase(), ` ${source} `] }), before = structuredClone(value);
  expect(automationErrors(value)).toEqual([]);
  const published = publicArtifact(value);
  expect(published.records.every(row => row.verdict === 'needsAnnotation' && row.autoGenerated)).toBe(true);
  expect(published.records[0].unsupported).toEqual([{ family: 'synthetic', code: 'eligibility-pending' }]);
  expect(value).toEqual(before);
});

test.each(pairs.map(({ owner }) => owner))('same-edition %s class-source casing remains valid', source => {
  const value = envelope(source, { level: 1, class: 'Synthetic Class', classSource: source.toLowerCase() });
  expect(automationErrors(value)).toEqual([]);
  expect(snapshotRecordErrors(value.records[0])).toEqual([]);
});

test('explicit extension editions are enforced while unclassified source codes are not assigned a guessed edition', () => {
  const modern = envelope('EXT', { level: 1, source: ['EXT', 'phb'] });
  modern.records.forEach(row => row.edition = '2024');
  expect(automationErrors(modern).map(error => error.code)).toEqual(['edition-reference']);
  const unknown = envelope('PHB', { level: 1, source: ['PHB', 'EXT'] });
  expect(automationErrors(unknown)).toEqual([]);
  expect(unknown.records[0].verdict).toBe('needsAnnotation');
});

test('the existing uppercase rejection remains the reference control', () => {
  expect(automationErrors(envelope('PHB', { level: 1, source: ['PHB', 'XPHB'] })).map(error => error.code)).toEqual(['edition-reference']);
});
