import { expect, test } from 'vitest';
import { createIdentity } from '../src/identity.ts';
import { deriveStructured } from '../src/derive/structured/index.ts';
import { makeContext } from '../src/derive/structured/common.ts';
import { automationErrors, validateAutomation } from '../src/validate/index.ts';
import type { Material } from '../src/derive/catalogue.ts';
import type { AutomationEnvelope, AutomationRecord, Edition } from '../src/protocol.ts';

const target = (edition?: Edition, name = 'Synthetic Option'): Material => ({
  identity: createIdentity({ kind: 'optionalfeature', source: 'EXT_OPT', engName: name }),
  raw: { ENG_name: name, name, source: 'EXT_OPT' }, edition,
  namespace: 'kiwee', files: ['data/synthetic.json'], expansion: 'source',
});
const owner = (edition?: Edition, options = ['Synthetic Option']): Material => {
  const source = edition === '2014' ? 'PHB' : edition === '2024' ? 'XPHB' : 'EXT_OWNER';
  return { identity: createIdentity({ kind: 'classFeature', source, engName: 'Synthetic Upgrade', classSource: source, classEngName: 'Synthetic Class', level: 2 }),
    raw: { entries: [{ type: 'options', count: 1, entries: options.map(name => ({ optionalfeature: `${name}|EXT_OPT` })) }] },
    edition, namespace: 'kiwee', files: ['data/synthetic.json'], expansion: 'source' };
};
const derive = (row: Material, choices: Material[]) => deriveStructured(row, makeContext([row, ...choices]));
const editions: Edition[] = ['2014', '2024', 'both'];

test.each(editions.flatMap(ownerEdition => editions.map(targetEdition => ({ ownerEdition, targetEdition }))))('typed choice $ownerEdition -> $targetEdition obeys explicit edition compatibility', ({ ownerEdition, targetEdition }) => {
  const row = owner(ownerEdition), option = target(targetEdition), out = derive(row, [option]);
  if (ownerEdition !== 'both' && targetEdition !== 'both' && ownerEdition !== targetEdition) {
    expect(out.mechanics.grants).toBeUndefined();
    expect(out.unsupported).toContainEqual({ family: 'inlineChoice', code: 'unresolved-inline-choice', ref: 'entries:0' });
  } else {
    expect(out.unsupported).toEqual([]);
    expect(out.mechanics).toEqual({ grants: [{ type: 'feature', choose: { count: 1, from: [option.identity.key] }, key: 'text-option:entries:0' }] });
  }
});

test('one incompatible single-edition option still rejects the whole group beside a shared option', () => {
  const row = owner('2014', ['Shared', 'Modern']), out = derive(row, [target('both', 'Shared'), target('2024', 'Modern')]);
  expect(out.mechanics.grants).toBeUndefined();
  expect(out.unsupported).toContainEqual({ family: 'inlineChoice', code: 'unresolved-inline-choice', ref: 'entries:0' });
});

test('a missing reference stays unresolved despite an explicitly shared owner', () => {
  const out = derive(owner('both'), []);
  expect(out.mechanics.grants).toBeUndefined();
  expect(out.unsupported).toContainEqual({ family: 'inlineChoice', code: 'unresolved-inline-choice', ref: 'entries:0' });
});

test('existing unknown-edition behavior is unchanged and no edition is inferred', () => {
  const row = owner(), option = target('2024'), before = structuredClone(row);
  const out = derive(row, [option]);
  expect(out.mechanics.grants).toHaveLength(1);
  expect(row).toEqual(before);
  expect(row.edition).toBeUndefined();
});

test('shared reference output validates as a pending draft without changing source data', () => {
  const row = owner('2024'), option = target('both'), before = structuredClone([row, option]);
  const freeze = (value: any): void => { if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); } };
  freeze(row); freeze(option);
  const out = derive(row, [option]);
  expect(out.mechanics.grants).toHaveLength(1);
  const records: AutomationRecord[] = [
    { identity: row.identity, edition: row.edition, verdict: 'needsAnnotation', autoGenerated: true, provenance: [{ layer: 'structured', ref: 'data/synthetic.json' }], mechanics: out.mechanics, unsupported: out.unsupported },
    { identity: option.identity, edition: option.edition, verdict: 'needsAnnotation', autoGenerated: true, provenance: [{ layer: 'structured', ref: 'data/synthetic.json' }], unsupported: [] },
  ];
  const envelope: AutomationEnvelope = { schemaVersion: 1, protocol: 3, versionLock: { kiweeChangelogVersion: 'synthetic', kiweeChangelogDate: '2026-10-14', fetchedAt: '2026-10-14T00:00:00Z', foundryMigrationVersion: [3], toolVersion: 'synthetic', inputs: [{ url: 'https://example.org/synthetic.json', path: 'synthetic.json', namespace: 'kiwee', role: 'catalog', sha256: 'a'.repeat(64), bytes: 1 }] }, records };
  expect(() => validateAutomation(envelope)).not.toThrow();
  expect(records.every(record => record.verdict === 'needsAnnotation' && record.autoGenerated)).toBe(true);
  expect(out.mechanics.modifiers).toBeUndefined();
  expect([row, option]).toEqual(before);
});

test('a forged both-edition tag on a core-book option remains invalid at the public boundary', () => {
  const row = owner('2024'), option = target('both');
  option.identity = createIdentity({ kind: 'optionalfeature', source: 'PHB', engName: 'Synthetic Option' });
  option.raw.source = 'PHB';
  row.raw.entries[0].entries[0].optionalfeature = 'Synthetic Option|PHB';
  const out = derive(row, [option]);
  const envelope: AutomationEnvelope = { schemaVersion: 1, protocol: 3,
    versionLock: { kiweeChangelogVersion: 'synthetic', kiweeChangelogDate: '2026-10-14', fetchedAt: '2026-10-14T00:00:00Z', foundryMigrationVersion: [3], toolVersion: 'synthetic', inputs: [{ url: 'https://example.org/synthetic.json', path: 'synthetic.json', namespace: 'kiwee', role: 'catalog', sha256: 'a'.repeat(64), bytes: 1 }] },
    records: [{ identity: row.identity, edition: row.edition, verdict: 'needsAnnotation', autoGenerated: true, provenance: [{ layer: 'structured', ref: 'data/synthetic.json' }], mechanics: out.mechanics, unsupported: out.unsupported },
      { identity: option.identity, edition: 'both', verdict: 'needsAnnotation', autoGenerated: true, provenance: [{ layer: 'structured', ref: 'data/synthetic.json' }], unsupported: [] }] };
  expect(automationErrors(envelope).map(error => error.code)).toContain('edition-source');
  expect(() => validateAutomation(envelope)).toThrow();
});
